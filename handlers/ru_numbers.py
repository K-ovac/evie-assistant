# ───────────────────────── Определение падежа по контексту ─────────────────────────

GEN_PREP = {"до", "от", "из", "без", "для", "около", "после", "у", "кроме", "вместо", "против", "возле",
            "среди", "вокруг", "свыше", "более", "менее", "порядка", "с", "со", "из-за", "изо", "течение"}
DAT_PREP = {"к", "ко", "благодаря", "согласно", "вопреки"}
INS_PREP = {"перед", "передо", "над", "надо", "между"}
PREP_PREP = {"в", "во", "на", "при", "о", "об", "обо"}
PREP_ONLY = {"при", "о", "об", "обо"}  # эти предлоги требуют только предложного падежа


def detect_case(prev, nxt=None):
    """
    Падеж числа по слову ПЕРЕД ним и слову ПОСЛЕ него.
    Если следующее слово стоит во множественном числе в косвенном падеже, берём падеж по его окончанию
    («к 5 часАМ» -> дательный). Иначе смотрим на предлог.
    «в/на/за» без других подсказок дают винительный (= именительный): «в 5 раз», «на 5 минут».
    """
    prev, nxt = (prev or "").lower(), (nxt or "").lower()
    if len(nxt) > 3:
        if nxt.endswith(("ами", "ями")):
            return "ins"
        if nxt.endswith(("ах", "ях")):
            return "prep"
        if nxt.endswith(("ам", "ям")):
            return "dat"
    if prev in ("с", "со") and nxt.endswith(("ой", "ей", "ом", "ем", "ём", "ью")):
        return "ins"  # «с 21 минутой», «с 1 часом» (единственное число)
    if prev in GEN_PREP:
        return "gen"
    if prev in DAT_PREP:
        return "dat"
    if prev in INS_PREP:
        return "ins"
    if prev in PREP_ONLY:
        return "prep"
    return "nom"


def case_after_prep(prev):
    """Падеж для года/порядкового, где «в/на/при/о» дают предложный."""
    prev = (prev or "").lower()
    if prev in PREP_PREP:
        return "prep"
    return detect_case(prev, None)


def guess_gender(noun, case, n):
    """Род для «один/два» по следующему слову («одна минута», «две минуты», «два часа»)."""
    noun = (noun or "").lower()
    last = n % 10 if n % 100 not in range(11, 15) else None
    if last == 1 and case in ("nom", "acc"):  # слово в им. падеже ед. числа
        if noun.endswith(("а", "я")):
            return "f"
        if noun.endswith(("о", "е")):
            return "n"
    elif last == 2 and case in ("nom", "acc"):  # слово в род. падеже ед. числа
        if noun.endswith(("ы", "и")):
            return "f"
    elif last == 1 and case == "gen":
        if noun.endswith(("ы", "и")):
            return "f"
    elif last == 1 and case == "dat":  # «к одной минуте» / «к одному часу»
        if noun.endswith(("е", "и")):
            return "f"
    elif last == 1 and case == "ins":  # «с одной минутой» / «с одним часом»
        if noun.endswith(("ой", "ей")):
            return "f"
    return "m"
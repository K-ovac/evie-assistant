def _decline_adj(word, case, gender, plural=False):
    idx = CASES.index(case)
    g = "pl" if plural else gender
    if word == "третий":
        return THIRD[g][idx]
    if g == "m":
        return word if case in ("nom", "acc") else word[:-2] + ("", "ого", "ому", "", "ым", "ом")[idx]
    return word[:-2] + HARD[g][idx]


def _ordinal_word(tok):
    if tok in ORD:
        return ORD[tok]
    if tok.endswith("надцать"):
        return tok[:-1] + "ый"
    return tok


def ordinal(n, case="nom", gender="m", plural=False):
    """ordinal(2026, 'prep') -> 'две тысячи двадцать шестом'. Склоняется только последнее слово."""
    tokens = num2words(int(n), lang="ru").split()
    last = tokens[-1]
    if last in BASE:  # круглые тысячи и миллионы: «двухтысячный»
        j = len(tokens) - 2
        while j >= 0 and tokens[j] not in BASE:
            j -= 1
        mult, head = tokens[j + 1:-1], tokens[:j + 1]
        stem = "".join(COMBINING.get(t, CARD[t][1]) for t in mult if t not in ("один", "одна"))
        word = stem + SCALE_ORD[BASE[last]]
    else:
        head, word = tokens[:-1], _ordinal_word(last)
    if head[:2] == ["одна", "тысяча"]:  # «в тысяча девятьсот девяносто девятом», без «одна»
        head = head[1:]
    return " ".join(head + [_decline_adj(word, case, gender, plural)])



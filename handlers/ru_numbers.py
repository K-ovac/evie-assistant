_ONE_G = {"f": "одна", "n": "одно"}


def _decline(tok, idx):
    forms = CARD.get(tok)
    return forms[idx] if forms else tok


def cardinal(n, case="nom", gender="m"):
    """cardinal(21, 'gen', 'f') -> 'двадцати одной'. gender влияет на «один/два» в конце числа."""
    tokens = num2words(int(n), lang="ru").split()
    if gender in ("f", "n") and tokens:
        if tokens[-1] == "один":
            tokens[-1] = _ONE_G[gender]
        elif tokens[-1] == "два" and gender == "f":
            tokens[-1] = "две"
    if case == "nom":
        return " ".join(tokens)

    idx = CASES.index(case)
    out, group = [], []
    for tok in tokens:
        if tok in BASE:
            out.extend(_decline(t, idx) for t in group)
            scale = SCALE[BASE[tok]]
            singular = bool(group) and group[-1] in ("один", "одна")
            if singular:
                out.append(scale["sing"][idx])
            elif case == "acc":
                out.append(tok)  # винительный = именительный
            else:
                out.append(scale["plur"][idx])
            group = []
        else:
            group.append(tok)
    out.extend(_decline(t, idx) for t in group)
    return " ".join(out)


